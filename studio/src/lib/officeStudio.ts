export interface ChartTableParams {
  title: string;
  type: "bar" | "line" | "pie" | "kpi";
  labels: string[];
  values: number[];
  seriesName?: string;
}

export async function generateChartTableXlsx(params: ChartTableParams): Promise<Buffer> {
  const { title, type, labels, values, seriesName = "Metric Value" } = params;

  const workbook = new ExcelJS.Workbook();
  const ws = workbook.addWorksheet(title.slice(0, 31) || "Visual Data");

  // Title Block
  ws.mergeCells("A1:C1");
  const titleCell = ws.getCell("A1");
  titleCell.value = `${title.toUpperCase()} (${type.toUpperCase()} SUMMARY)`;
  titleCell.font = { bold: true, size: 14, color: { argb: "FFFFFFFF" } };
  titleCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0F172A" } };
  titleCell.alignment = { horizontal: "center", vertical: "middle" };
  ws.getRow(1).height = 30;

  // Header
  ws.getRow(3).values = ["Category / Period", seriesName, "Percentage of Total"];
  ws.getRow(3).font = { bold: true, color: { argb: "FFFFFFFF" } };
  ws.getRow(3).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF2563EB" } };
  ws.getRow(3).height = 22;

  const total = values.reduce((a, b) => a + b, 0) || 1;

  labels.forEach((lbl, idx) => {
    const val = values[idx] ?? 0;
    const pct = `${((val / total) * 100).toFixed(1)}%`;
    const row = ws.addRow([lbl, val, pct]);
    row.height = 20;
    if (idx % 2 === 1) {
      row.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF8FAFC" } };
    }
  });

  // Summary Row
  const totalRow = ws.addRow(["TOTAL", total, "100.0%"]);
  totalRow.font = { bold: true };
  totalRow.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE2E8F0" } };

  ws.columns = [
    { key: "cat", width: 26 },
    { key: "val", width: 18 },
    { key: "pct", width: 22 },
  ];

  return Buffer.from(await workbook.xlsx.writeBuffer());
}

