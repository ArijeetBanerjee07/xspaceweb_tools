export interface InvoiceItem {
  description: string;
  quantity: number;
  unitPrice: number;
}

export interface InvoiceParams {
  invoiceNumber: string;
  date: string;
  dueDate: string;
  from: { name: string; address: string; email: string; taxId?: string };
  billTo: { name: string; address: string; email: string };
  items: InvoiceItem[];
  currency?: string;
  taxRatePercent?: number;
  notes?: string;
}

export async function generateInvoiceDocx(params: InvoiceParams): Promise<Buffer> {
  const {
    invoiceNumber,
    date,
    dueDate,
    from,
    billTo,
    items,
    currency = "INR",
    taxRatePercent = 18,
    notes = "Payment is due within 15 days of invoice date. Thank you for your business!",
  } = params;

  const subtotal = items.reduce((sum, item) => sum + item.quantity * item.unitPrice, 0);
  const taxAmount = (subtotal * taxRatePercent) / 100;
  const grandTotal = subtotal + taxAmount;

  const itemRows = items.map(
    (it) =>
      new TableRow({
        children: [
          new TableCell({ children: [new Paragraph({ text: it.description })] }),
          new TableCell({ children: [new Paragraph({ text: String(it.quantity), alignment: AlignmentType.RIGHT })] }),
          new TableCell({
            children: [
              new Paragraph({
                text: `${currency} ${it.unitPrice.toLocaleString()}`,
                alignment: AlignmentType.RIGHT,
              }),
            ],
          }),
          new TableCell({
            children: [
              new Paragraph({
                text: `${currency} ${(it.quantity * it.unitPrice).toLocaleString()}`,
                alignment: AlignmentType.RIGHT,
              }),
            ],
          }),
        ],
      })
  );

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: convertInchesToTwip(0.8),
              bottom: convertInchesToTwip(0.8),
              left: convertInchesToTwip(0.8),
              right: convertInchesToTwip(0.8),
            },
          },
        },
        children: [
          new Paragraph({
            children: [
              new TextRun({ text: "INVOICE", bold: true, size: 36, color: "1E40AF" }),
            ],
            spacing: { after: 100 },
          }),
          new Paragraph({
            children: [
              new TextRun({ text: `Invoice #: ${invoiceNumber}`, bold: true }),
              new TextRun({ text: `    Date: ${date}    Due Date: ${dueDate}`, color: "555555" }),
            ],
            spacing: { after: 300 },
          }),

          // Sender & Client Table
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [
              new TableRow({
                children: [
                  new TableCell({
                    children: [
                      new Paragraph({ children: [new TextRun({ text: "BILLED FROM:", bold: true, size: 20 })] }),
                      new Paragraph({ text: from.name }),
                      new Paragraph({ text: from.address }),
                      new Paragraph({ text: from.email }),
                      ...(from.taxId ? [new Paragraph({ text: `GST/Tax ID: ${from.taxId}` })] : []),
                    ],
                  }),
                  new TableCell({
                    children: [
                      new Paragraph({ children: [new TextRun({ text: "BILLED TO:", bold: true, size: 20 })] }),
                      new Paragraph({ text: billTo.name }),
                      new Paragraph({ text: billTo.address }),
                      new Paragraph({ text: billTo.email }),
                    ],
                  }),
                ],
              }),
            ],
          }),

          new Paragraph({ text: "", spacing: { after: 200 } }),

          // Items Table
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [
              new TableRow({
                children: [
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Item Description", bold: true })] })] }),
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Qty", bold: true })], alignment: AlignmentType.RIGHT })] }),
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Unit Price", bold: true })], alignment: AlignmentType.RIGHT })] }),
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Total", bold: true })], alignment: AlignmentType.RIGHT })] }),
                ],
              }),
              ...itemRows,
              new TableRow({
                children: [
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Subtotal", bold: true })] })], columnSpan: 3 }),
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: `${currency} ${subtotal.toLocaleString()}`, bold: true })], alignment: AlignmentType.RIGHT })] }),
                ],
              }),
              new TableRow({
                children: [
                  new TableCell({ children: [new Paragraph({ text: `Tax (${taxRatePercent}%)` })], columnSpan: 3 }),
                  new TableCell({ children: [new Paragraph({ text: `${currency} ${taxAmount.toLocaleString()}`, alignment: AlignmentType.RIGHT })] }),
                ],
              }),
              new TableRow({
                children: [
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "GRAND TOTAL", bold: true, size: 24, color: "1E40AF" })] })], columnSpan: 3 }),
                  new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: `${currency} ${grandTotal.toLocaleString()}`, bold: true, size: 24, color: "1E40AF" })], alignment: AlignmentType.RIGHT })] }),
                ],
              }),
            ],
          }),

          new Paragraph({ text: "", spacing: { after: 300 } }),
          new Paragraph({
            children: [
              new TextRun({ text: "Payment Terms & Notes:", bold: true }),
              new TextRun({ text: `\n${notes}` }),
            ],
          }),
        ],
      },
    ],
  });

  return await Packer.toBuffer(doc);
}

