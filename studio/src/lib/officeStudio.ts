export interface FormulaSuggestion {
  formula: string;
  description: string;
  syntax: string;
  exampleData: { columns: string[]; rows: any[][] };
  calculatedResult: string | number;
  tips: string[];
}

export function suggestSpreadsheetFormula(prompt: string): FormulaSuggestion {
  const p = prompt.toLowerCase();

  if (
    p.includes("sumif") ||
    (p.includes("sum") &&
      (p.includes("where") ||
        p.includes("condition") ||
        p.includes("status") ||
        p.includes("region") ||
        p.includes("if") ||
        p.includes("filter")))
  ) {
    return {
      formula: '=SUMIFS(D2:D100, B2:B100, "North", C2:C100, "Paid")',
      description: "Sums values in column D where column B equals 'North' and column C equals 'Paid'.",
      syntax: "SUMIFS(sum_range, criteria_range1, criterion1, [criteria_range2, criterion2, ...])",
      exampleData: {
        columns: ["Order ID", "Region", "Status", "Amount ($)"],
        rows: [
          [101, "North", "Paid", 1250],
          [102, "South", "Paid", 800],
          [103, "North", "Pending", 450],
          [104, "North", "Paid", 2100],
        ],
      },
      calculatedResult: "$3,350",
      tips: [
        "SUMIFS supports multiple criteria; the sum_range is always the first parameter.",
        "Wrap text criteria in quotation marks.",
      ],
    };
  }

  if (p.includes("vlookup") || p.includes("xlookup") || p.includes("lookup") || p.includes("find in table")) {
    return {
      formula: '=XLOOKUP(F2, A2:A100, C2:C100, "Not Found", 0)',
      description: "Searches for lookup value F2 in column A and returns matching item from column C.",
      syntax: "XLOOKUP(lookup_value, lookup_array, return_array, [if_not_found], [match_mode])",
      exampleData: {
        columns: ["Employee ID", "Name", "Department", "Salary ($)"],
        rows: [
          ["EMP01", "Alice Chen", "Engineering", 95000],
          ["EMP02", "Marcus Roy", "Marketing", 72000],
          ["EMP03", "Priya Nair", "Operations", 84000],
        ],
      },
      calculatedResult: "Engineering (for EMP01)",
      tips: [
        "XLOOKUP replaces VLOOKUP; it doesn't break if you insert or move columns.",
        "You can supply a friendly fallback message if the item isn't located.",
      ],
    };
  }

  if (p.includes("countif") || p.includes("count unique") || p.includes("count where")) {
    return {
      formula: '=COUNTIFS(B2:B100, "Completed", C2:C100, ">100")',
      description: "Counts rows where status is 'Completed' and quantity exceeds 100.",
      syntax: "COUNTIFS(criteria_range1, criterion1, ...)",
      exampleData: {
        columns: ["Task ID", "Status", "Hours Logged"],
        rows: [
          ["TSK-1", "Completed", 120],
          ["TSK-2", "In Progress", 40],
          ["TSK-3", "Completed", 95],
          ["TSK-4", "Completed", 150],
        ],
      },
      calculatedResult: "2",
      tips: ["Comparison operators like > and < must be enclosed in double quotes (e.g., '>100')."],
    };
  }

  if (p.includes("compound") || p.includes("interest") || p.includes("loan") || p.includes("emi")) {
    return {
      formula: "=PMT(Rate/12, NPER*12, -LoanAmount)",
      description: "Calculates monthly loan installment (EMI) based on constant payments and interest rate.",
      syntax: "PMT(rate, nper, pv, [fv], [type])",
      exampleData: {
        columns: ["Loan Principal ($)", "Annual Interest Rate", "Loan Term (Years)", "Monthly EMI"],
        rows: [[100000, "7.5%", 15, "$927.01"]],
      },
      calculatedResult: "$927.01 / month",
      tips: ["Ensure interest rate and time periods use matching frequencies (e.g. rate / 12 for monthly payments)."],
    };
  }

  // Default intelligent formula suggestion
  return {
    formula: '=IF(B2>1000, B2*0.9, B2)',
    description: "Applies a 10% discount if the amount in B2 exceeds 1,000; otherwise keeps standard price.",
    syntax: "IF(logical_test, [value_if_true], [value_if_false])",
    exampleData: {
      columns: ["Product", "Base Price ($)", "Calculated Price ($)"],
      rows: [
        ["Pro Suite", 1200, 1080],
        ["Starter Pack", 450, 450],
        ["Enterprise Kit", 2500, 2250],
      ],
    },
    calculatedResult: "1,080",
    tips: [
      "Combine IF with AND/OR for complex logical tests.",
      "Use IFERROR(formula, fallback) to prevent #N/A or #DIV/0! errors.",
    ],
  };
}

