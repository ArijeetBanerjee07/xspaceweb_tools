// 9. Spreadsheet-to-Document Automation (Mail Merge)
// ==========================================
export interface MergeParams {
  templateText: string;
  rows: Record<string, string>[];
  fileNamePrefix?: string;
}

export async function generateSpreadsheetToDocMerge(params: MergeParams): Promise<Buffer> {
  const { templateText, rows, fileNamePrefix = "Document" } = params;

  const zip = new JSZip();

  for (let i = 0; i < rows.length; i++) {
    const row = rows[i];
    let mergedText = templateText;

    // Replace all {{key}} with row[key]
    Object.keys(row).forEach((k) => {
      const reg = new RegExp(`{{\\s*${k}\\s*}}`, "gi");
      mergedText = mergedText.replace(reg, String(row[k] || ""));
    });

    const doc = new Document({
      sections: [
        {
          children: [
            new Paragraph({
              text: `${fileNamePrefix} - Record #${i + 1}`,
              heading: HeadingLevel.TITLE,
              spacing: { after: 300 },
            }),
            ...mergedText.split(/\n\s*\n/).map(
              (p) =>
                new Paragraph({
                  children: [new TextRun({ text: p.trim(), size: 22 })],
                  spacing: { after: 150 },
                })
            ),
          ],
        },
      ],
    });

    const docBuffer = await Packer.toBuffer(doc);
    const recipientName = row.Name || row.name || row.Client || `Row_${i + 1}`;
    const safeName = String(recipientName).replace(/[^a-zA-Z0-9_-]/g, "_");
    zip.file(`${fileNamePrefix}_${i + 1}_${safeName}.docx`, docBuffer);
  }

  // Also include a summary CSV log
  const headers = Object.keys(rows[0] || {}).join(",");
  const csvContent = [headers, ...rows.map((r) => Object.values(r).join(","))].join("\n");
  zip.file("merge_summary.csv", csvContent);

  return await zip.generateAsync({ type: "nodebuffer" });
}

