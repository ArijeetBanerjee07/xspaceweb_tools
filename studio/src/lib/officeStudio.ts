// 2. DOCX Generation
// ==========================================
export interface DocxParams {
  title: string;
  author?: string;
  content: string; // Plain text or paragraphs
  sections?: { heading: string; body: string }[];
}

export async function generateDocx(params: DocxParams): Promise<Buffer> {
  const { title, author = "Office Studio", content, sections } = params;

  const children: Paragraph[] = [
    new Paragraph({
      text: title,
      heading: HeadingLevel.TITLE,
      spacing: { after: 200 },
    }),
    new Paragraph({
      children: [
        new TextRun({
          text: `Author: ${author}  |  Created: ${new Date().toLocaleDateString()}`,
          italics: true,
          color: "666666",
        }),
      ],
      spacing: { after: 400 },
    }),
  ];

  if (sections && sections.length > 0) {
    for (const sec of sections) {
      children.push(
        new Paragraph({
          text: sec.heading,
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 250, after: 120 },
        }),
        new Paragraph({
          children: [new TextRun({ text: sec.body, size: 22 })],
          spacing: { after: 200 },
        })
      );
    }
  } else {
    const rawParagraphs = content.split(/\n\s*\n/).filter((p) => p.trim().length > 0);
    for (const p of rawParagraphs) {
      children.push(
        new Paragraph({
          children: [new TextRun({ text: p.trim(), size: 22 })],
          spacing: { after: 180 },
        })
      );
    }
  }

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: convertInchesToTwip(1),
              bottom: convertInchesToTwip(1),
              left: convertInchesToTwip(1),
              right: convertInchesToTwip(1),
            },
          },
        },
        children,
      },
    ],
  });

  return await Packer.toBuffer(doc);
}

