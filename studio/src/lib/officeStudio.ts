export interface AiDocumentParams {
  title: string;
  brief: string;
  docType?: "proposal" | "agreement" | "memo" | "sop" | "policy";
  tone?: "professional" | "formal" | "concise" | "persuasive";
  customSections?: { heading: string; body: string }[];
  fullText?: string;
  mode?: "sections" | "full";
}

export async function generateAiDocument(params: AiDocumentParams): Promise<Buffer> {
  const { title, brief, docType = "proposal", tone = "professional", customSections, fullText, mode } = params;

  let bodyParagraphs: Paragraph[] = [];

  if (mode === "full" && fullText && fullText.trim()) {
    const rawParagraphs = fullText.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
    bodyParagraphs = rawParagraphs.map((p) => {
      const isHeading = /^(\d+\.|\#{1,3}\s|\*{2}.+\*{2}$)/.test(p) && p.length < 90;
      if (isHeading) {
        return new Paragraph({
          text: p.replace(/^(\#{1,3}\s|\*{2})/g, "").replace(/\*{2}$/g, "").trim(),
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 280, after: 120 },
        });
      }
      return new Paragraph({
        children: [new TextRun({ text: p, size: 22 })],
        spacing: { after: 150 },
      });
    });
  } else {
    // Use custom user-edited sections if provided; otherwise generate based on brief
    const sections =
      customSections && customSections.length > 0
        ? customSections.map((s) => ({ heading: s.heading, paragraphs: s.body.split(/\n\s*\n/).filter(Boolean) }))
        : buildAiSections(title, brief, docType, tone);

    bodyParagraphs = sections.flatMap((s) => [
      new Paragraph({
        text: s.heading,
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 300, after: 150 },
      }),
      ...s.paragraphs.map(
        (p) =>
          new Paragraph({
            children: [new TextRun({ text: p, size: 22 })],
            spacing: { after: 150 },
          })
      ),
    ]);
  }

  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: convertInchesToTwip(1),
              bottom: convertInchesToTwip(1),
              left: convertInchesToTwip(1),
              right: convertInchesToTwip(1),
            },
          },
        },
        children: [
          new Paragraph({
            text: title.toUpperCase(),
            heading: HeadingLevel.TITLE,
            alignment: AlignmentType.CENTER,
            spacing: { after: 300 },
          }),
          new Paragraph({
            alignment: AlignmentType.CENTER,
            children: [
              new TextRun({
                text: `Document Type: ${docType.toUpperCase()}  |  Tone: ${tone.toUpperCase()}  |  Generated by Office Studio AI`,
                italics: true,
                color: "555555",
                size: 20,
              }),
            ],
            spacing: { after: 500 },
          }),
          ...bodyParagraphs,
          new Paragraph({
            text: "Authorization & Signatures",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 400, after: 200 },
          }),
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [
              new TableRow({
                children: [
                  new TableCell({
                    children: [
                      new Paragraph({ children: [new TextRun({ text: "Prepared By: ___________________", bold: true })] }),
                      new Paragraph({ text: "Date: _________________________" }),
                    ],
                  }),
                  new TableCell({
                    children: [
                      new Paragraph({ children: [new TextRun({ text: "Approved By: ___________________", bold: true })] }),
                      new Paragraph({ text: "Date: _________________________" }),
                    ],
                  }),
                ],
              }),
            ],
          }),
        ],
      },
    ],
  });

  return await Packer.toBuffer(doc);
}

function buildAiSections(title: string, brief: string, docType: string, tone: string) {
  const cleanTitle = title.trim() || "Business Document";
  const cleanBrief = brief.trim() || `Comprehensive analysis and strategic overview for ${cleanTitle}`;
  const intro = `This ${docType} outlines critical perspectives and actionable context for "${cleanTitle}". Formulated with a ${tone} approach to address the primary focus: "${cleanBrief}".`;

  if (docType === "agreement") {
    return [
      {
        heading: "1. Purpose & Parties",
        paragraphs: [
          intro,
          `This Agreement establishes the mutual terms, covenants, and responsibilities governing "${cleanTitle}".`,
        ],
      },
      {
        heading: "2. Scope of Engagement & Deliverables",
        paragraphs: [
          `Key requirements and obligations: ${cleanBrief}.`,
          `All milestones shall adhere to verified standards, schedules, and deliverables for "${cleanTitle}".`,
        ],
      },
      {
        heading: "3. Terms, Governing Law & Execution",
        paragraphs: [
          "Both parties maintain mutual obligations of confidentiality, compliance, and dispute resolution under applicable law.",
        ],
      },
    ];
  }

  if (docType === "sop") {
    return [
      {
        heading: "1. Standard Operating Procedure Overview",
        paragraphs: [intro, `Establishes reproducible procedures and quality protocols for "${cleanTitle}".`],
      },
      {
        heading: "2. Operational Workflow & Execution",
        paragraphs: [
          `Step 1: Intake & Validation — Verify prerequisites and core inputs relating to ${cleanBrief}.`,
          `Step 2: Processing & Core Execution — Carry out standard procedures for "${cleanTitle}" according to approved guidelines.`,
          `Step 3: Quality Review & Signoff — Inspect output for compliance prior to final distribution or archival.`,
        ],
      },
      {
        heading: "3. Exception Handling & Escalation",
        paragraphs: [
          `Any anomalies or critical deviations relating to "${cleanTitle}" must be documented in the log and escalated promptly.`,
        ],
      },
    ];
  }

  // Default proposal / memo / policy
  return [
    {
      heading: "1. Executive Summary",
      paragraphs: [
        intro,
        `Provides an authoritative synthesis of "${cleanTitle}" to guide decision-making, mitigate risks, and establish strategic alignment.`,
      ],
    },
    {
      heading: "2. Core Analysis & Key Drivers",
      paragraphs: [
        `Detailed exploration of core requirement: ${cleanBrief}.`,
        `Direct implications for "${cleanTitle}": evaluating essential variables, primary challenges, and measurable impact.`,
        `Strategic considerations designed to ensure clarity, stakeholder buy-in, and effective execution.`,
      ],
    },
    {
      heading: "3. Strategic Recommendations & Action Plan",
      paragraphs: [
        `Priority 1: Implement targeted actions directly addressing ${cleanBrief}.`,
        `Priority 2: Establish continuous tracking, feedback loops, and accountability measures for "${cleanTitle}".`,
        `Priority 3: Maintain active oversight to ensure desired outcomes are achieved according to designated timelines.`,
      ],
    },
  ];
}

