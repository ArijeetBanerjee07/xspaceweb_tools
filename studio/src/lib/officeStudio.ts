// 3. Excel / XLSX Creation
// ==========================================
export interface XlsxParams {
  title: string;
  sheetName?: string;
  columns: { header: string; key: string; width?: number }[];
  rows: Record<string, any>[];
}

export async function generateXlsx(params: XlsxParams): Promise<Buffer> {
  const { title, sheetName = "Sheet1", columns, rows } = params;

  const workbook = new ExcelJS.Workbook();
  workbook.creator = "Office Studio";
  workbook.created = new Date();

  const worksheet = workbook.addWorksheet(sheetName.slice(0, 31));

  worksheet.columns = columns.map((col) => ({
    header: col.header,
    key: col.key,
    width: col.width || Math.max(col.header.length + 5, 14),
  }));

  // Style header row
  const headerRow = worksheet.getRow(1);
  headerRow.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 11 };
  headerRow.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "FF1E40AF" }, // Indigo / Navy
  };
  headerRow.alignment = { vertical: "middle", horizontal: "center" };
  headerRow.height = 24;

  // Add data rows with light border & alternating stripes
  rows.forEach((r, idx) => {
    const row = worksheet.addRow(r);
    row.height = 20;
    if (idx % 2 === 1) {
      row.fill = {
        type: "pattern",
        pattern: "solid",
        fgColor: { argb: "FFF8FAFC" },
      };
    }
    row.eachCell({ includeEmpty: true }, (cell) => {
      cell.border = {
        top: { style: "thin", color: { argb: "FFE2E8F0" } },
        bottom: { style: "thin", color: { argb: "FFE2E8F0" } },
        left: { style: "thin", color: { argb: "FFE2E8F0" } },
        right: { style: "thin", color: { argb: "FFE2E8F0" } },
      };
      if (typeof cell.value === "number") {
        cell.alignment = { horizontal: "right" };
      }
    });
  });

  return Buffer.from(await workbook.xlsx.writeBuffer());
}

