function splitFullTextIntoSections(fullText: string): { heading: string; body: string }[] {
  const blocks = fullText.split(/\n(?=(?:\d+\.|\b(?:Executive Summary|Introduction|Overview|Background|Analysis|Findings|Key Points|Recommendations|Conclusion|Action Plan)\b))/i);
  const sections: { heading: string; body: string }[] = [];
  for (const block of blocks) {
    const trimmed = block.trim();
    if (!trimmed) continue;
    const lines = trimmed.split("\n");
    const heading = lines[0].replace(/^#+\s*/, "").trim();
    const body = lines.slice(1).join("\n").trim();
    if (heading && body) {
      sections.push({ heading, body });
    } else if (heading) {
      sections.push({ heading, body: heading });
    }
  }
  return sections.length > 0 ? sections : [{ heading: "1. Document Overview", body: fullText.trim() }];
}

